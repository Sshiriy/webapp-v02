export function getPathway(slug: string) {
  return pathways.find((item) => item.slug === slug);
}

export function stagesFor(pathway: Pathway, phase: CarePhase) {
  if (phase === "unsure") return pathway.stages;
  return pathway.stages.filter((stage) => stage.phase === phase);
}

export function phaseLabel(phase: CarePhase) {
  return phases.find((item) => item.id === phase)?.label ?? "نامشخص";
}
